// 无限加载
const observeBox = () => {
  // 获取要监听的元素
  box = document.querySelector(".observe");

  observe = new IntersectionObserver(
    (entries) => {
      entries.forEach(async (e) => {
        if (e.isIntersecting && e.intersectionRatio > 0) {
          if (!musicListLoading.value) {
            loadMore();
          }
        }
      });
    },
    { threshold: [1] }
  );
  box && observe.observe(box);
};

